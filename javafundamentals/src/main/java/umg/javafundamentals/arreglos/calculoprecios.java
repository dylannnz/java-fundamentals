    private void btncalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalcularActionPerformed
        // TODO add your handling code here:
        
        String texto = txtprecios.getText();
        String[] numeros = texto.split(",");
        double[] precios = new double[numeros.length];
        for (int i = 0; i < numeros.length ;i++) {
        precios[i]= Double.parseDouble(numeros[i]);
    }
        double suma = 0;
        for (int i = 0; i < precios.length ;i++) {
         suma += precios[i];
    }
        double impuesto = suma*0.12;
        double total = impuesto+suma;
        
        lbltotal.setText("El total a pagar es: " + total);
        lblimpuesto.setText("El impuesto pagado es: " + impuesto);
    }//GEN-LAST:event_btncalcularActionPerformed

