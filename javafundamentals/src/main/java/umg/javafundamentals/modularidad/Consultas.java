    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
    
    if (indice < nombres.length) {

        
        String nombre = txtNombre.getText();
        double precio = Double.parseDouble(txtPrecio.getText());

        nombres[indice] = nombre;
        precios[indice] = precio;
        
        indice++;
        
        limpiar();
        
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Ya no hay espacio para más productos");
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarActionPerformed
    try {
        java.io.FileWriter fw = new java.io.FileWriter("productos.csv", false);

        for (int i = 0; i < indice; i++) {
            fw.write(nombres[i] + "," + precios[i] + "\n");
        }

        fw.close();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Productos guardados correctamente");

    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error al guardar el archivo");
    }
    }//GEN-LAST:event_GuardarActionPerformed

