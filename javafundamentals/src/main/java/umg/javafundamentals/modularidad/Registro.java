    public void leerArchivoCSV() {

        totalLeidos = 0;

        java.io.File archivo = new java.io.File("productos.csv");

        try (java.util.Scanner sc = new java.util.Scanner(archivo)) {

          while (sc.hasNextLine()) {

               String linea = sc.nextLine();
               String[] partes = linea.split(",");


                   catalogoNombres[totalLeidos] = partes[0];
                   catalogoPrecios[totalLeidos] = Double.parseDouble(partes[1]);

                   totalLeidos++;
          }

        } catch (java.io.FileNotFoundException e) {

         javax.swing.JOptionPane.showMessageDialog(
                this, "No se encontró el archivo productos.csv");

        }
    }
    
        
    public double calcularTotalInventario() {

        double suma = 0;

        for (int i = 0; i < totalLeidos; i++) {
            suma += catalogoPrecios[i];
        }

            return suma;
    }
    
    
    public void mostrarEnPantalla() {

        taCatalogo.setText("");

        for (int i = 0; i < totalLeidos; i++) {

            taCatalogo.append(
                (i + 1) + ". " + catalogoNombres[i] + " - Q" + catalogoPrecios[i] + "\n"
            );
        }

        double total = calcularTotalInventario();

        taCatalogo.append(
            "\nValor Total del Inventario: Q" + total
        );
    }
